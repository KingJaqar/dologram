import { color, typeTokens, space, radius, motion, z, elevation, avatarFills } from './tokens.ts';
import { iconSizes } from './icons.ts';

const kebab = (value: string) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function flatten(value: object, prefix: string, unit = ''): string[] {
  return Object.entries(value).flatMap(([key, entry]: [string, unknown]) => {
    const name = `${prefix}-${kebab(key)}`;
    if (typeof entry === 'object' && entry !== null) return flatten(entry, name, unit);
    return [`  ${name}: ${String(entry)}${typeof entry === 'number' ? unit : ''};`];
  });
}

function theme(scheme: 'light' | 'dark'): string {
  const values = color[scheme];
  return [
    ...flatten(values, '--dg-color'),
    '  --dg-color-danger: var(--dg-color-danger-text);',
    ...Object.entries(elevation).map(([key, value]) =>
      `  --dg-elevation-${key}: 0 ${value.android}px ${value.android * 4}px color-mix(in srgb, var(--dg-color-shadow) ${(scheme === 'light' ? value.shadowOpacityLight : value.shadowOpacityDark) * 100}%, transparent);`),
  ].join('\n');
}

/** Pure deterministic CSS projection. Font variables are supplied by next/font. */
export function generateTokensCss(): string {
  const typography = Object.entries(typeTokens).flatMap(([key, value]) => {
    const name = `--dg-type-${kebab(key)}`;
    const family = value.family === 'Inter' ? 'sans' : 'mono';
    return [
      `  ${name}: ${value.weight} ${value.size / 16}rem/${value.lineHeight / 16}rem var(--dg-font-${family});`,
      `  ${name}-letter-spacing: ${value.letterSpacing}px;`,
    ];
  });
  return [
    '/* Generated by npm run tokens. Edit tokens.ts/icons.ts, then regenerate. */',
    ':root {',
    ...flatten(space, '--dg-space', 'px'),
    ...flatten(radius, '--dg-radius', 'px'),
    ...flatten(motion.duration, '--dg-motion-duration', 'ms'),
    ...flatten(motion.delay, '--dg-motion-delay', 'ms'),
    ...flatten(motion.toast, '--dg-motion-toast', 'ms'),
    ...flatten(motion.easing, '--dg-motion-easing'),
    ...flatten(z, '--dg-z'),
    ...Object.entries(iconSizes).flatMap(([key, value]) => [
      `  --dg-icon-${key}: ${value.size}px;`, `  --dg-icon-${key}-stroke: ${value.stroke};`,
    ]),
    ...typography,
    theme('light'),
    '}',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {', theme('dark'), '  }', '}',
    ':root[data-theme="dark"] {', theme('dark'), '}',
    '',
  ].join('\n');
}

/** Web-only compatibility aliases; current shared values remain authoritative. */
export function generateWebTokensCss(): string {
  const bubbleAliases = {
    'out-bg': 'outgoing', 'out-text': 'outgoingText',
    'in-bg': 'incoming', 'in-text': 'incomingText',
  } satisfies Record<string, keyof typeof color.light.bubble>;
  const aliases = Object.entries(bubbleAliases).map(([alias, source]) =>
    `  --dg-color-bubble-${alias}: var(--dg-color-bubble-${kebab(source)});`);
  return generateTokensCss() + [
    ':root {', ...aliases,
    ...avatarFills.map((fill, index) => `  --dg-avatar-fill-${index}: ${fill};`),
    `  --dg-avatar-text: ${color.light.badge.muted.text};`,
    `  --dg-motion-spinner-period: ${motion.duration.spinner}ms;`,
    '  --dg-motion-duration-base: var(--dg-motion-duration-normal);',
    '}',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...Object.keys(motion.duration).filter((key) => key !== 'fast').map((key) =>
      `    --dg-motion-duration-${kebab(key)}: 0ms;`),
    '    --dg-motion-duration-base: 0ms;',
    '  }', '}', '',
  ].join('\n');
}
