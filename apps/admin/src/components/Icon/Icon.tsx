export interface IconProps { name: IconName; size?: IconSize; label?: string; className?: string }

export function Icon({ name, size = 'md', label, className }: IconProps) {
  const Component = icons[iconNames[name]];
  const dimensions = iconSizes[size];
  return <Component size={dimensions.size} strokeWidth={dimensions.stroke} className={className}
    role={label ? 'img' : undefined} aria-label={label} aria-hidden={label ? undefined : true} focusable="false" />;
}
